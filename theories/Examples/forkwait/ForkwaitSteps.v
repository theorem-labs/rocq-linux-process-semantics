(* ===================================================================== *)
(* [machine_run]: a bounded run of ORDINARY instruction steps             *)
(* ===================================================================== *)

(** [machine_run segs k ms] takes exactly [k] machine steps from [ms], and
    answers [None] the moment one of them is not an ordinary instruction
    step: a fault, an unmodeled word, or a state whose [ms_svc_pending] is
    already set — a system call appeared before the segment was over.

    That last case is the one the consumer needs: a [Some] answer says
    every INTERMEDIATE state of the segment had no call pending, which is
    what the successor case of a whole-system halting predicate asks for.
    The final state is exempt: [k = O] answers [Some ms] without the test,
    so a segment may (and here always does) END on a pending call.

    [Common/CatSim.msteps] is this relation without the index;
    [machine_run_msteps] below is the bridge, for the consumer that wants
    its transitivity and [StepTac]'s step tactics. *)
Fixpoint machine_run (segs : list Segment) (k : nat) (ms : machine_state)
    : option machine_state :=
  match k with
  | O => Some ms
  | S k' =>
      match ms_svc_pending ms with
      | Some _ => None
      | None =>
        match RiscvSemantics.step segs ms with
        | MachineOk ms' => machine_run segs k' ms'
        | _ => None
        end
      end
  end.

(** One step of a [machine_run], in the shape the per-instruction step
    lemmas close: the [reflexivity | step lemma | continue] idiom of
    theories/Examples/rwx_flag_ns/rwx_flag_ns_source.v. *)
Lemma mrun_step : forall segs k ms ms' r,
  ms_svc_pending ms = None ->
  RiscvSemantics.step segs ms = MachineOk ms' ->
  machine_run segs k ms' = r ->
  machine_run segs (S k) ms = r.
Proof.
  intros segs k ms ms' r Hsvc Hstep Hrun.
  cbn [machine_run]. rewrite Hsvc, Hstep. exact Hrun.
Qed.

Lemma machine_run_msteps : forall segs k ms ms',
  machine_run segs k ms = Some ms' -> msteps segs ms ms'.
Proof.
  intros segs k. induction k as [|k IH]; intros ms ms' H.
  - cbn [machine_run] in H. injection H as <-. apply mst_refl.
  - cbn [machine_run] in H.
    destruct (ms_svc_pending ms) eqn:Hsvc; [discriminate|].
    destruct (RiscvSemantics.step segs ms) as [ms1| |] eqn:Hstep;
      try discriminate.
    eapply mst_step; [exact Hsvc | exact Hstep | apply IH; exact H].
Qed.

(** Any state with no pending call and no reservation IS a [mkst], which is
    the form the per-instruction step lemmas — and every segment below —
    are stated over.  The consumer rewrites with this to hand a state its
    own arms built (a [Procs.child_ms], an [advance_past_svc
    (apply_effect ...)]) to a segment lemma.

    Both hypotheses hold everywhere in a run of this program:
    [Run.init_machine_state] sets [ms_resv := None] and
    [ms_svc_pending := None], [mkst] sets both, [advance_past_svc] clears
    the call and preserves the reservation, [apply_effect] preserves it,
    and forkwait contains no [lr]/[sc]. *)
Lemma mkst_eta : forall ms : machine_state,
  ms_svc_pending ms = None -> ms_resv ms = None ->
  ms = @mkst (mkFP (ms_fregs ms) (ms_fcsr ms))
             (ms_regs ms) (ms_pc ms) (ms_mem ms) (ms_rom ms).
Proof.
  intros [regs fregs pc svc resv fcsr mem rom] Hsvc Hresv.
  cbn in *. subst. reflexivity.
Qed.

(** [ms_gpr st i] is x(10+i) ([RiscvSemantics.v:115-118]), so argument
    index [i] is the physical register [r] this lemma's first hypothesis
    names.  a0 is index 0 and x10; index 10 would be x20. *)
Lemma ms_gpr_getr : forall (st : machine_state) (i : nat) (r : reg),
  Z_to_bv 5 (10 + Z.of_nat i) = r -> bv_eqb r 0 = false ->
  ms_gpr st i = getr (ms_regs st) r.
Proof.
  intros st i r Hr Hz. unfold ms_gpr, getr. rewrite Hr, Hz. reflexivity.
Qed.

