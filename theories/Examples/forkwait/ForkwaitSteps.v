Lemma fw_run_A : forall regs mem rom,
  machine_run forkwait_segs 7 (mkst regs 0x11000 mem rom)
  = Some (ecall_st (fw_regs_A regs) 0x11018 mem rom).
Proof.
  intros regs mem rom. unfold fw_regs_A.
  (* 0x11000 li a0, 17 — SIGCHLD, the whole flag word *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 17);
      [exact SF_11000 | reflexivity | exact SD_11000 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x11004 li a1, 0 — newsp *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 0);
      [exact SF_11004 | reflexivity | exact SD_11004 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x11008 li a2, 0 — parent_tidptr *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 0);
      [exact SF_11008 | reflexivity | exact SD_11008 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x1100c li a3, 0 — tls *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 0);
      [exact SF_1100c | reflexivity | exact SD_1100c | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x11010 li a4, 0 — child_tidptr *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 0);
      [exact SF_11010 | reflexivity | exact SD_11010 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x11014 li a7, 220 — __NR_clone *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 220);
      [exact SF_11014 | reflexivity | exact SD_11014 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x11018 ecall *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_ecall_st; [exact SF_11018 | reflexivity]
    | ].
  reflexivity.
Qed.

