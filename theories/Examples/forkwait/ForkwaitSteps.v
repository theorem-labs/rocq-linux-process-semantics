(** x0 reads as zero, as a SIGNED zero: what [bltz] compares against. *)
Lemma fw_signed_zero : bv_signed (Z_to_bv 64 0) = 0%Z.
Proof. vm_compute. reflexivity. Qed.

(** A word below 2^63 is its own signed value: the pid the clone returns is
    far below it, so [bltz] is not taken for it. *)
Lemma fw_signed_small : forall x : word,
  (bv_unsigned x < 2 ^ 63)%Z -> bv_signed x = bv_unsigned x.
Proof.
  intros x Hx. pose proof (bv_unsigned_in_range 64 x) as Hr.
  unfold bv_signed, bv_swrap, bv_wrap, bv_half_modulus, bv_modulus in *.
  cbn in *. rewrite Z.mod_small; lia.
Qed.

