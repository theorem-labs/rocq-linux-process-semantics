Ltac fw_gpr r :=
  rewrite (ms_gpr_getr _ _ r) by (first [ bveq | vm_compute; reflexivity ]);
  cbn [ms_regs ecall_st];
  unfold fw_regs_A, fw_regs_exit7, fw_regs_P, fw_regs_C;
  getr_resolve; reflexivity.

Ltac fw_svc :=
  cbn [ms_svc_pending ecall_st];
  unfold fw_regs_A, fw_regs_exit7, fw_regs_P, fw_regs_C;
  getr_resolve; reflexivity.

(** Segment A ends on clone(SIGCHLD, 0, 0, 0, 0).  a0 is given in full
    because [Fork.clone_fork_flags_b] tests the whole 64-bit word. *)
Lemma fw_A_svc : forall regs pc mem rom,
  ms_svc_pending (ecall_st (fw_regs_A regs) pc mem rom) = Some 220.
Proof. intros. fw_svc. Qed.

Lemma fw_A_a0 : forall regs pc mem rom,
