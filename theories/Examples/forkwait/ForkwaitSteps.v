(** The readback hypothesis of [fw_run_reap], discharged from the memory a
    reap arm leaves: [Run.apply_effect]'s write path is [apply_writes], one
    declared range is [write_to_mem], and [write_to_mem] IS [CatExec.wbytes]
    — so [SeqExec.rdn_wbytes_hit] reads the four bytes straight back.  The
    only side condition is that the slot does not wrap the address space,
    which the entry stack window gives.

    Stated over the WRITE, not over an effect record, so it does not care
    what else the arm declared as long as the status range is the one it
    wrote. *)
Lemma fw_slot_read : forall (mem : word -> option byte) (a status : word),
  (bv_unsigned a + 4 <= 2 ^ 64)%Z ->
  (bv_unsigned status = 256 * 7)%Z ->
  rdn forkwait_segs
      (apply_writes mem [(a, Z_to_le_bytes 4 (bv_unsigned status))]) a 4
  = Some (Z_to_le_bytes 4 1792).
Proof.
  intros mem a status Hnw Hst. cbn [apply_writes].
  rewrite write_to_mem_wbytes, Hst.
  change (256 * 7)%Z with 1792%Z.
  pose proof (rdn_wbytes_hit forkwait_segs (Z_to_le_bytes 4 1792) mem a) as H.
  rewrite length_Z_to_le_bytes in H. apply H. exact Hnw.
Qed.


(** The status is taken as a READ-BACK, not as the consumer's effect term:
    [apply_effect]'s write path is [apply_writes mem [(a, bs)] =
    write_to_mem mem a bs] and [write_to_mem] is [CatExec.wbytes], so
    [SeqExec.rdn_wbytes_hit] discharges this hypothesis from a reap arm
    that wrote [Z_to_le_bytes 4 (bv_unsigned status)] at the slot, given
    [bv_unsigned status = 256 * 7] and no address wrap.

    1792 = 7 << 8 is positive, so the SIGNED [lw] sign-extends nothing and
    [srli] by 8 recovers 7.  This is the only arithmetic in the program. *)
Lemma fw_run_reap : forall regs mem rom (sp : word),
  getr regs 2 = fw_slot sp ->
  rdn forkwait_segs mem (fw_slot sp) 4 = Some (Z_to_le_bytes 4 1792) ->
  machine_run forkwait_segs 4 (mkst regs 0x11040 mem rom)
  = Some (ecall_st (fw_regs_C regs) 0x1104c mem rom).
Proof.
  intros regs mem rom sp Hsp Hmem. unfold fw_regs_C.
  (* 0x11040 lw a0, 0(sp) — the status word *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_lw with (bs := Z_to_le_bytes 4 1792) (v := 1792);
      [exact SF_11040 | reflexivity | exact SD_11040
      | rewrite Hsp; imm_norm; rewrite v_addi_0; exact Hmem
      | vm_compute; reflexivity]
    | fw_simpl ].
  replace (v_lw 1792) with (1792 : word) by bveq.
  (* 0x11044 srli a0, a0, 8 — WEXITSTATUS *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_srli_at with (v := 7);
      [exact SF_11044 | reflexivity | exact SD_11044 | reflexivity
      | getr_resolve; imm_norm; bveq]
    | fw_simpl ].
  (* 0x11048 li a7, 94 — __NR_exit_group *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 94);
      [exact SF_11048 | reflexivity | exact SD_11048 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x1104c ecall *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_ecall_st; [exact SF_1104c | reflexivity]
    | ].
  reflexivity.
Qed.

