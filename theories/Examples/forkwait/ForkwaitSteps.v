(* Segment parent: 0x1101c with a0 = a pid, to wait4 at 0x1103c           *)
(* ===================================================================== *)

(** [q] stays a VARIABLE: the two bounds are what
    [Sys.Kernel.Fork.clone_pid_ok_b] guarantees of a clone's return, they
    are exactly what makes both branches fall through, and [q] is dead
    after [li a0, -1].  The sp bounds are the entry window's, as
    rwx_flag_ns_source.v quantifies them. *)
Lemma fw_run_parent : forall regs mem rom (q sp : word),
  getr regs 10 = q ->
  getr regs 2 = sp ->
  (0 < bv_unsigned q)%Z ->
  (bv_unsigned q < 2 ^ 22)%Z ->
  (16 <= bv_unsigned sp)%Z ->
  machine_run forkwait_segs 9 (mkst regs 0x1101c mem rom)
  = Some (ecall_st (fw_regs_P regs sp) 0x1103c mem rom).
Proof.
  intros regs mem rom q sp Ha0 Hsp Hq0 Hq1 Hsp16.
  assert (Hqs : bv_signed q = bv_unsigned q)
    by (apply fw_signed_small; lia).
  unfold fw_regs_P.
  (* 0x1101c bltz a0, .Lfail — a pid is positive *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_branch_ft_gen;
      [exact SF_1101c | reflexivity | exact SD_1101c
      | rewrite Ha0, getr_zero; cbn [branch_taken]; unfold bv_lts;
        rewrite fw_signed_zero, Hqs; apply Z.ltb_nlt; lia]
    | fw_simpl ].
  (* 0x11020 beqz a0, .Lchild — not taken: this IS the parent *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_branch_ft_gen;
      [exact SF_11020 | reflexivity | exact SD_11020
      | rewrite Ha0, getr_zero; cbn [branch_taken]; unfold bv_eqb;
        rewrite u_Z2bv by lia; apply Z.eqb_neq; lia]
    | fw_simpl ].
  (* 0x11024 addi sp, sp, -16 — the status slot *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := fw_slot sp);
      [exact SF_11024 | reflexivity | exact SD_11024 | reflexivity
      | rewrite Hsp; imm_norm; unfold fw_slot;
        apply v_addi_m16; lia]
    | fw_simpl ].
  (* 0x11028 li a0, -1 — upid = -1, any child *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 0xffffffffffffffff);
      [exact SF_11028 | reflexivity | exact SD_11028 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x1102c mv a1, sp — &status *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := fw_slot sp);
      [exact SF_1102c | reflexivity | exact SD_1102c | reflexivity
      | getr_resolve; imm_norm; apply v_addi_0]
    | fw_simpl ].
  (* 0x11030 li a2, 0 — options = 0, BLOCKING *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 0);
      [exact SF_11030 | reflexivity | exact SD_11030 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x11034 li a3, 0 — rusage = NULL *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 0);
      [exact SF_11034 | reflexivity | exact SD_11034 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x11038 li a7, 260 — __NR_wait4 *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_addi_at with (v := 260);
      [exact SF_11038 | reflexivity | exact SD_11038 | reflexivity | fw_li]
    | fw_simpl ].
  (* 0x1103c ecall *)
  eapply mrun_step;
    [ reflexivity
    | eapply step_ecall_st; [exact SF_1103c | reflexivity]
    | ].
  reflexivity.
Qed.

