(** Normalize the chained pc to its numeral-literal form, so the next
    instruction's generated fetch lemma matches.  [StepTac.norm_pc] does
    this for the chain relations it knows; [machine_run] is not one of
    them, and [norm_pc_state] is the piece it is built from. *)
Ltac fw_simpl :=
  reduce_bv_eqb_ifs;
  try lazymatch goal with
  | |- machine_run _ _ ?st = _ => norm_pc_state st
  end.

(** The writeback value of an [li]/[addi] whose source is x0. *)
Ltac fw_li := getr_resolve; imm_norm; bveq.

(** A branch condition over resolved registers: closed, so the vm decides
    it. *)
Ltac fw_cond := getr_resolve; vm_compute; reflexivity.

