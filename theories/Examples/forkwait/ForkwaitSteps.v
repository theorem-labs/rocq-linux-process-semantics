(** After the six [li] of the entry: the clone's arguments and a7. *)
Definition fw_regs_A (regs : bvmap 5 word) : bvmap 5 word :=
  regupd (regupd (regupd (regupd (regupd (regupd regs
    10 17) 11 0) 12 0) 13 0) 14 0) 17 220.

(** Either tail that exits 7: a0 = 7, a7 = __NR_exit_group. *)
Definition fw_regs_exit7 (regs : bvmap 5 word) : bvmap 5 word :=
  regupd (regupd regs 10 7) 17 94.

(** The status slot [wait4] is given: sp - 16, after the frame push. *)
Definition fw_slot (sp : word) : word := Z_to_bv 64 (bv_unsigned sp - 16).

(** After the parent's prologue: the pushed sp, upid = -1, &status,
    options = 0, rusage = NULL, a7 = __NR_wait4. *)
Definition fw_regs_P (regs : bvmap 5 word) (sp : word) : bvmap 5 word :=
  regupd (regupd (regupd (regupd (regupd (regupd regs
    2 (fw_slot sp)) 10 0xffffffffffffffff) 11 (fw_slot sp)) 12 0) 13 0)
    17 260.

(** After the reap tail: a0 is loaded, then shifted, so x10 is written
    twice — the [lw]'s value and then [WEXITSTATUS] of it. *)
Definition fw_regs_C (regs : bvmap 5 word) : bvmap 5 word :=
  regupd (regupd (regupd regs 10 1792) 10 7) 17 94.

