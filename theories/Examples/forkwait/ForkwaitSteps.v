(** The slot's address, spelled out: the reap arm writes four bytes there
    and must know where. *)
Lemma fw_slot_addr : forall sp : word,
  (16 <= bv_unsigned sp)%Z ->
  (bv_unsigned (fw_slot sp) = bv_unsigned sp - 16)%Z.
Proof.
  intros sp H. unfold fw_slot. rewrite u_Z2bv by
    (pose proof (bv_unsigned_in_range 64 sp);
     change (bv_modulus 64) with (2 ^ 64)%Z in *; lia).
  reflexivity.
Qed.

