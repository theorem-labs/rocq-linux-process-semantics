(** * Examples.forkwait.ForkwaitSteps — forkwait's four machine segments

    PROOF-SIDE FILE (not part of the trusted specification).

    [source/forkwait.S] is 26 instructions and three system calls, so it is
    NOT a straight line and no whole-program predicate describes it.  What
    the multi-process relation needs instead, and what this file delivers,
    is the four maximal runs of ORDINARY instructions between the calls —
    plus a fifth for the errno path the program also handles:

      A     entry (0x11000) to the clone's [ecall]       (7 steps)
      child the clone's resume point with a0 = 0,
            to [exit_group(7)]                            (5 steps)
      parent the same resume point with a0 = a pid,
            to [wait4]                                    (9 steps)
      reap  after the reap, to [exit_group(status >> 8)]  (4 steps)
      fail  the resume point with a negative a0,
            to [exit_group(7)]                            (4 steps)

    NOTHING HERE MENTIONS A [Model], A PROCESS TABLE OR A [pconfig].  Every
    segment is about [RiscvSemantics.step] alone.  That is deliberate:
    [Run.mi_account_step_no_lazy] says an accounted step with no lazy
    mapping IS [RiscvSemantics.step] and leaves the model fixed, and
    [State.init_model] gives no lazy mappings, so the model side of the
    whole run is discharged once by the consumer rather than threaded
    through five lemmas here.

    EACH SEGMENT IS QUANTIFIED OVER AN ARBITRARY REGISTER FILE AND MEMORY,
    with hypotheses naming only what that segment reads.  It has to be: the
    state the clone arm hands the child is [Procs.child_ms], which is
    [set_reg (cfg_ms c') 10 0] over a register file that ALREADY carries the
    parent's return value, hence a double update at x10 — not syntactically
    the state one would write by hand, and a lemma pinned to one spelling
    would not apply to the other.  [mkst_eta] below puts any state the
    consumer holds into the form these lemmas are about.

    THE INSTRUCTION COUNTS INCLUDE THE [ecall].  The model executes the
    [ecall] WORD as an ordinary machine step that sets [ms_svc_pending]
    ([ShapeNodes.ecall_st]); the syscall layer then fires from the state
    that step left.  So a segment that must end on [ms_svc_pending = Some n]
    takes one more step than it has instructions before the call.

    The fetch and decode facts come from [forkwait_code], generated by
    tools/gen_fd_lemmas.py out of the committed snapshot (see
    theories/Examples/dune); the image's executable segment is r-x, so they
    are over the plain [fetch_word] and no overlay reasoning arises. *)

